const isEgyptian = (herb) => herb.egypt !== null;

// بيرجع العلاجات للحالة مع بيانات العشبة، مع فلترة اختيارية
function getRemedies(conditionId, { egyptianOnly = false, pregnancySafe = false } = {}) {
  const c = HEALTH_CONDITIONS.find((x) => x.id === conditionId);
  if (!c) return [];
  return c.remedies
    .map((r) => ({ ...r, ...HERBS[r.herb], herbId: r.herb, img: herbImage(r.herb) }))
    .filter((r) => !egyptianOnly || isEgyptian(r))
    .filter((r) => !pregnancySafe || r.pregnancy === 'ok');
}

function groupByCategory() {
  return HEALTH_CONDITIONS.reduce((acc, c) => {
    (acc[c.category] ||= []).push(c);
    return acc;
  }, {});
}

function searchConditions(q) {
  const t = q.trim();
  if (!t) return HEALTH_CONDITIONS;
  return HEALTH_CONDITIONS.filter(
    (c) =>
      c.name.includes(t) ||
      c.desc.includes(t) ||
      c.remedies.some((r) => HERBS[r.herb].name.includes(t) || HERBS[r.herb].latin.toLowerCase().includes(t.toLowerCase()))
  );
}

// فحص سريع للبيانات: شغّله في الـ console وهو بيطلعلك أي غلطة
function validateData() {
  const errors = [];
  const ids = new Set();
  HEALTH_CONDITIONS.forEach((c) => {
    if (ids.has(c.id)) errors.push(`id مكرر: ${c.id}`);
    ids.add(c.id);
    c.remedies.forEach((r) => {
      if (!HERBS[r.herb]) errors.push(`العشبة "${r.herb}" مش موجودة (في ${c.id})`);
      if (!EVIDENCE[r.evidence]) errors.push(`evidence غلط في ${c.id}/${r.herb}`);
    });
  });
  Object.entries(HERBS).forEach(([id, h]) => {
    if (!PREGNANCY[h.pregnancy]) errors.push(`pregnancy غلط في ${id}`);
    if (!('egypt' in h) || !('planting' in h)) errors.push(`حقول ناقصة في ${id}`);
  });
  BLENDS.forEach((b) =>
    b.herbs.forEach((h) => { if (!HERBS[h]) errors.push(`خلطة "${b.name}": عشبة مجهولة ${h}`); })
  );
  const unused = Object.keys(HERBS).filter(
    (id) => !HEALTH_CONDITIONS.some((c) => c.remedies.some((r) => r.herb === id)) && !BLENDS.some((b) => b.herbs.includes(id))
  );
  if (unused.length) errors.push(`أعشاب مش مستخدمة: ${unused.join(', ')}`);
  return errors.length ? errors : ['✅ البيانات سليمة'];
}

